function normalizeMode(value) {
  const mode = String(value || 'analyze').trim();
  return MODES.has(mode) ? mode : 'analyze';
}

function normalizeApprovalMode(value) {
  const mode = String(value || 'required').trim().toLowerCase();
  return ['required', 'workspace_auto', 'never'].includes(mode) ? mode : 'required';
}

function roleForMode(mode) {
  if (mode === 'build') return 'builder';
  if (mode === 'analyze') return 'analyst';
  return 'researcher';
}

function normalizeRole(value) {
  const role = String(value || '').trim();
  if (!ROLES.has(role)) throw subagentError('SUBAGENT_ROLE_INVALID', `Unsupported subagent role: ${role}.`, 400);
  return role;
}

function normalizeTaskId(value) {
  const id = String(value || '').trim();
  if (!/^[A-Za-z0-9_.:-]{1,120}$/u.test(id)) throw subagentError('SUBAGENT_TASK_ID_INVALID', 'Subagent task IDs must be short stable identifiers.', 400);
  return id;
}

function toolDefinition({ name, description, inputSchema, risk = 'read', idempotent = true, parallelSafe = true }) {
  return Object.freeze({
    name,
    title: name,
    description,
    version: '1.0.0',
    category: 'agent',
    tags: ['agent', 'subagent', 'delegation'],
    scopes: [],
    risk,
    idempotent,
    parallelSafe,
    inputSchema,
  });
}

function objectSchema(properties = {}, required = []) {
  return { type: 'object', additionalProperties: false, properties, required };
}

function uniqueTools(tools) {
  return [...new Map(tools.map((tool) => [tool.name, tool])).values()];
}

function toolSummary(tool) {
  return {
    name: tool.name,
    title: tool.title || tool.name,
    description: tool.description || '',
    category: tool.category || 'general',
    risk: tool.risk || 'read',
    scopes: Array.isArray(tool.scopes) ? tool.scopes : [],
    idempotent: tool.idempotent !== false,
    parallelSafe: tool.parallelSafe !== false,
    source: tool.source || 'unknown',
  };
}

function toolReceipt(call, ok, value) {
  return {
    toolCallId: String(call.id || ''),
    toolName: String(call.name || ''),
    status: ok ? 'completed' : 'failed',
    ...(ok
      ? { outputType: valueType(value) }
      : { error: publicError(value) }),
  };
}

function valueType(value) {
  if (Array.isArray(value)) return 'array';
  if (value === null) return 'null';
  return typeof value;
}

function toolErrorResult(call, error) {
  return { type: 'tool.error', name: String(call.name || ''), error: publicError(error) };
}

function publicError(error) {
  return {
    code: String(error?.code || 'SUBAGENT_TOOL_FAILED'),
    message: String(error?.message || error || 'Operation failed.').slice(0, 2_000),
  };
}

function emitEvent(context, event, now) {
  if (typeof context?.emit !== 'function') return;
  try {
    context.emit({ ...event, createdAt: event.createdAt || now().toISOString() });
  } catch {
    // Event projection must not change subagent execution semantics.
  }
}

function compactValue(value, maxChars) {
  const serialized = safeStringify(value);
  if (serialized.length <= maxChars) {
    try { return JSON.parse(serialized); } catch { return serialized; }
  }
  return { truncated: true, preview: serialized.slice(0, Math.max(0, maxChars - 80)), originalChars: serialized.length };
}

function serializeForModel(value, maxChars) {
  const serialized = safeStringify(value);
  if (serialized.length <= maxChars) return serialized;
  return JSON.stringify({ truncated: true, preview: serialized.slice(0, Math.max(0, maxChars - 100)), originalChars: serialized.length });
}

function safeStringify(value) {
  try { return JSON.stringify(value); } catch { return JSON.stringify(String(value)); }
}

function wireToolName(name) {
  return `copilot_${String(name || '').replaceAll('.', '__')}`;
}

function arrayOfStrings(value) {
  return [...new Set((Array.isArray(value) ? value : []).map((item) => String(item || '').trim()).filter(Boolean))].slice(0, 100);
}

function requiredText(value, name, maximum) {
  const text = String(value || '').trim();
  if (!text) throw subagentError('SUBAGENT_VALUE_REQUIRED', `${name} is required.`, 400);
  return text.slice(0, maximum);
}

function bounded(value, fallback, minimum, maximum) {
  const number = Number(value);
  return Number.isFinite(number) ? Math.max(minimum, Math.min(maximum, Math.trunc(number))) : fallback;
}

function assertNotAborted(signal) {
  if (!signal?.aborted) return;
  throw subagentError('SUBAGENT_ABORTED', 'Subagent execution was aborted.', 409);
}

function subagentError(code, message, status = 400) {
  const error = new Error(message);
  error.name = 'SubagentRuntimeError';
  error.code = code;
  error.status = status;
  error.recoverable = status >= 500 || ['SUBAGENT_ABORTED', 'SUBAGENT_STEP_LIMIT'].includes(code);
  return error;
}
