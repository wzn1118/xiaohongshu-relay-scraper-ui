function receiptForState(state, governance = null) {
  const nodes = Array.isArray(state?.nodes) ? state.nodes : [];
  const contract = state?.turn?.contract || {};
  const counts = Object.fromEntries(['pending', 'running', 'completed', 'failed', 'cancelled'].map((status) => [status, nodes.filter((node) => node.status === status).length]));
  return {
    receiptId: state?.run ? `subagent:${state.run.runId}:r${state.run.planRevision}` : '',
    runId: state?.run?.runId || '',
    parentRunId: String(contract.parentRunId || firstNodeInput(state)?.parentRunId || ''),
    parentToolRunId: String(contract.parentToolRunId || firstNodeInput(state)?.parentToolRunId || ''),
    conversationId: state?.run?.conversationId || '',
    status: state?.run?.status || 'unknown',
    planRevision: Number(state?.run?.planRevision || 0),
    objective: state?.turn?.goal || '',
    persisted: Boolean(state?.run),
    active: Boolean(state?.active),
    resumable: ['paused', 'failed', 'queued'].includes(String(state?.run?.status || '')),
    bounds: contract.bounds || {},
    counts,
    tasks: nodes.map((node) => ({
      taskId: node.nodeId,
      role: String(node.input?.role || String(node.kind || '').replace(/^subagent\./u, '')),
      title: node.title,
      dependsOn: node.dependsOn || [],
      status: node.status,
      attemptCount: Number(node.attemptCount || 0),
      summary: String(node.output?.text || '').slice(0, 1_000),
      error: node.error?.message ? { code: node.error.code, message: String(node.error.message).slice(0, 1_000) } : null,
    })),
    governance: governance || null,
    startedAt: state?.run?.startedAt || '',
    completedAt: state?.run?.completedAt || '',
    updatedAt: state?.run?.updatedAt || '',
  };
}

function compactResults(nodes, maxChars) {
  const results = [];
  let remaining = maxChars;
  for (const node of Array.isArray(nodes) ? nodes : []) {
    if (node.status !== 'completed' || !node.output) continue;
    const text = String(node.output.text || '');
    const available = Math.max(0, remaining - 500);
    const boundedText = text.slice(0, available);
    results.push({
      taskId: node.nodeId,
      role: node.output.role || node.input?.role || '',
      title: node.title,
      text: boundedText,
      truncated: Boolean(node.output.truncated || boundedText.length < text.length),
      steps: node.output.steps,
      toolCallCount: node.output.toolCallCount,
      tools: node.output.tools || [],
      provider: node.output.provider,
      model: node.output.model,
    });
    remaining -= boundedText.length + 500;
    if (remaining <= 0) break;
  }
  return results;
}

function taskEventSummary(task) {
  if (!task) return { taskId: '', role: '', title: '', dependsOn: [] };
  return {
    taskId: task.id,
    role: task.input?.role || String(task.kind || '').replace(/^subagent\./u, ''),
    title: task.title,
    dependsOn: task.dependsOn || [],
  };
}

function eventIdentity({ runId, parent, conversationId }) {
  return {
    runId: String(runId || ''),
    parentRunId: String(parent?.parentRunId || ''),
    parentToolRunId: String(parent?.parentToolRunId || ''),
    conversationId: String(conversationId || parent?.conversationId || ''),
  };
}

function normalizeParentContext(context) {
  const reference = normalizeReference(context.reference);
  const conversationId = String(reference?.conversationId || context.conversation?.conversationId || context.conversationId || '').trim();
  if (!conversationId) throw subagentError('SUBAGENT_CONVERSATION_REQUIRED', 'A bound conversation is required for delegation.', 400);
  return {
    conversationId,
    parentRunId: requiredText(context.runId || context.parentRunId, 'parentRunId', 200),
    parentToolRunId: requiredText(context.toolRunId || context.parentToolRunId, 'parentToolRunId', 200),
  };
}

function parentFromState(state, context = {}) {
  const contract = state.turn?.contract || {};
  return {
    conversationId: state.run?.conversationId || context.reference?.conversationId || '',
    parentRunId: String(contract.parentRunId || firstNodeInput(state)?.parentRunId || context.runId || ''),
    parentToolRunId: String(contract.parentToolRunId || firstNodeInput(state)?.parentToolRunId || context.toolRunId || ''),
  };
}

function assertConversationOwnership(state, context) {
  if (!context || typeof context !== 'object') return;
  const reference = normalizeReference(context.reference);
  const conversationId = String(reference?.conversationId || context.conversation?.conversationId || context.conversationId || '').trim();
  if (conversationId && conversationId !== state.run?.conversationId) {
    throw subagentError('SUBAGENT_RUN_CONTEXT_MISMATCH', 'The subagent run does not belong to this conversation.', 409);
  }
}

function firstNodeInput(state) {
  return state?.nodes?.[0]?.input || {};
}

function normalizeReference(value) {
  if (!value || typeof value !== 'object') return null;
  return {
    conversationId: String(value.conversationId || ''),
    jobId: String(value.jobId || ''),
    snapshotId: String(value.snapshotId || ''),
    mode: String(value.mode || ''),
    scope: compactValue(value.scope || {}, 8_000),
  };
}

function normalizeConversation(value, reference) {
  if (!value || typeof value !== 'object') return reference ? normalizeReference(reference) : null;
  return {
    conversationId: String(value.conversationId || reference?.conversationId || ''),
    jobId: String(value.jobId || reference?.jobId || ''),
    snapshotId: String(value.snapshotId || reference?.snapshotId || ''),
    mode: String(value.mode || reference?.mode || ''),
    scope: compactValue(value.scope || reference?.scope || {}, 8_000),
    filters: compactValue(value.filters || {}, 8_000),
  };
}

